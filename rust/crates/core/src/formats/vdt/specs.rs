use crate::formats::{
    catalog::CatalogProfile,
    common::{
        keys, ContainerKind, DefaultArchivePipeline, FamilyIdentity, FormatCapabilities,
        FormatCatalog, FormatFamily, FormatFamilySpec, FormatKey, FormatKeys, FormatSpec,
        HintScopedProfileResolver, NoCrypto, NoFooter,
    },
    sl1::adapters::PngLayerCodec,
    FormatIdentity,
};

use super::adapters::{VdtArchiveHeaderLayout, VdtArchiveLayout};

static VDT_HEADER: VdtArchiveHeaderLayout = VdtArchiveHeaderLayout;
static VDT_ARCHIVE: VdtArchiveLayout = VdtArchiveLayout;
static PNG_CODEC: PngLayerCodec = PngLayerCodec;

/// Runtime spec for Voxeldance VDT ZIP archives.
///
/// VDT uses PNG grayscale layer images plus VDT-specific manifest/config entries
/// generated by the archive layout.
///
/// Voxeldance VDT ZIP archive 的运行期 spec。VDT 使用 PNG grayscale layer images，
/// 并由 archive layout 生成 VDT-specific manifest/config entries。
pub static VDT_SPEC: FormatSpec = FormatSpec {
    identity: FormatIdentity {
        name: "vdt",
        aliases: &["vdt"],
        extensions: &["vdt"],
    },
    family: FormatFamily::Vdt,
    catalog: FormatCatalog {
        profile_id: "voxeldance-vdt-archive",
        display_name: "Voxeldance VDT archive",
        default_extension: "vdt",
        target_names: &["vdt"],
        default_export: true,
    },
    container: ContainerKind::Archive,
    capabilities: FormatCapabilities::archive_import_export()
        .with_preview(true)
        .with_per_layer_settings(true),
    keys: FormatKeys {
        family_key: keys::FAMILY_VDT,
        profile_key: FormatKey("profile/voxeldance-vdt-archive"),
        container_key: keys::CONTAINER_ARCHIVE,
        header_key: keys::HEADER_VDT_ARCHIVE,
        layer_codec_key: keys::PNG_GRAYSCALE,
        pixel_model_key: keys::PIXEL_PNG_GRAYSCALE,
        crypto_key: keys::NO_CRYPTO,
        footer_key: keys::NO_FOOTER,
        archive_key: keys::ZIP_ARCHIVE,
    },
    header: &VDT_HEADER,
    layer_codec: &PNG_CODEC,
    crypto: &NoCrypto,
    footer: &NoFooter,
    archive: &VDT_ARCHIVE,
    pipeline: &DefaultArchivePipeline,
};

/// Runtime profiles published by the VDT family.
///
/// VDT family 暴露给 runtime registry 的 profiles。
pub static PROFILES: &[&FormatSpec] = &[&VDT_SPEC];

/// Catalog wrapper for the generic VDT profile.
///
/// generic VDT profile 的 catalog wrapper。
pub static VDT_PROFILE: CatalogProfile = CatalogProfile::Generic(&VDT_SPEC);

/// Catalog profiles exported to the WASM/TypeScript format catalog.
///
/// 导出到 WASM/TypeScript format catalog 的 VDT profiles。
pub static CATALOG_PROFILES: &[&CatalogProfile] = &[&VDT_PROFILE];

static RESOLVER: HintScopedProfileResolver = HintScopedProfileResolver;

/// Family-level registry entry for Voxeldance VDT.
///
/// Voxeldance VDT 的 family-level registry entry。
pub static FAMILY: FormatFamilySpec = FormatFamilySpec {
    identity: FamilyIdentity {
        name: "vdt",
        aliases: &["vdt", "voxeldance"],
        extensions: &["vdt"],
    },
    family: FormatFamily::Vdt,
    profiles: PROFILES,
    resolver: &RESOLVER,
};
